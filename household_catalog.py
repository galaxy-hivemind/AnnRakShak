# Build immutable tuple of HouseholdItem instances
HOUSEHOLD_CATALOG: list[HouseholdItem] = [
    HouseholdItem(
        id=item["id"],
        name=item["name"],
        subtitle=item["subtitle"],
        category=item["category"],
        aliases=tuple(item["aliases"]),
        badge_color=item["badge_color"],
        accent_color=item["accent_color"],
        icon_type=item["icon_type"],
    )
    for item in ITEMS_RAW
]

# Quick index by ID
HOUSEHOLD_BY_ID: dict[str, HouseholdItem] = {item.id: item for item in HOUSEHOLD_CATALOG}


def normalize_query_text(text: str) -> str:
    """Normalize query text for fuzzy keyword matching."""
    if not text:
        return ""
    clean = text.lower()
    clean = re.sub(r"['’]s\b", "", clean)
    clean = re.sub(r"[^a-z0-9\s]", " ", clean)
    return " ".join(clean.split())


def find_best_household_item(
    product_name: str | None,
    brand: str | None = None,
    category: str | None = None,
) -> HouseholdItem | None:
    """
    Match product against the curated 200 common household items catalog.
    Uses exact alias matching, token overlap scoring, and category alignment.
    Guarantees:
      - 'Milkybar' matches white-chocolate (NOT milk)
      - 'Osmania Biscuits' / 'DBH' matches osmania-biscuits
      - 'Tropicana Frutz Litchi Love' matches litchi-juice
    """
    if not product_name and not brand:
        return None

    full_query = f"{brand or ''} {product_name or ''}".strip()
    norm_query = normalize_query_text(full_query)
    norm_p = normalize_query_text(product_name or "")
    if not norm_query:
        return None

    query_tokens = set(norm_query.split())

    # 1. Exact alias match (full string match)
    for item in HOUSEHOLD_CATALOG:
        for alias in item.aliases:
            norm_alias = normalize_query_text(alias)
            if norm_alias == norm_query or norm_alias == norm_p:
                return item

    # 1b. Whole phrase contained - pick the most specific (longest / highest token count) phrase match
    best_phrase_item: HouseholdItem | None = None
    best_phrase_score = 0
    for item in HOUSEHOLD_CATALOG:
        for alias in item.aliases:
            norm_alias = normalize_query_text(alias)
            pattern = rf"\b{re.escape(norm_alias)}\b"
            if re.search(pattern, norm_query):
                p_tokens = len(norm_alias.split())
                score = p_tokens * 100 + len(norm_alias)
                if category and item.category.lower() in category.lower():
                    score += 10
                if score > best_phrase_score:
                    best_phrase_score = score
                    best_phrase_item = item

    if best_phrase_item is not None:
        return best_phrase_item

    # 2. Token overlap ranking with negative weights for conflicting terms
    best_item: HouseholdItem | None = None
    best_score = 0.0

    # Words that should not trigger wrong items (e.g. 'milkybar' should not match 'milk')
    for item in HOUSEHOLD_CATALOG:
        score = 0.0
        for alias in item.aliases:
            norm_alias = normalize_query_text(alias)
            alias_tokens = set(norm_alias.split())
            if not alias_tokens:
                continue

            # Exact subset match
            if alias_tokens.issubset(query_tokens):
                score = max(score, 50.0 + len(alias_tokens) * 10.0)
            else:
                overlap = query_tokens.intersection(alias_tokens)
                if overlap:
                    ratio = len(overlap) / len(alias_tokens)
                    score = max(score, ratio * 35.0)

        # Category bonus
        if category and item.category.lower() in category.lower():
            score += 5.0

        if score > best_score:
            best_score = score
            best_item = item

    if best_score >= 25.0:
        return best_item

    return None
